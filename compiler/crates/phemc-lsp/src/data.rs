pub fn element(name: &str) -> Option<(&'static str, bool)> {
    ELEMENTS.iter().find(|e| e.0 == name).map(|e| (e.1, e.2))
}

pub fn global_attribute(name: &str) -> Option<&'static str> {
    GLOBAL_ATTRIBUTES.iter().find(|a| a.0 == name).map(|a| a.1)
}

pub fn attributes_for(tag: &str) -> &'static [&'static str] {
    ELEMENT_ATTRIBUTES.iter().find(|e| e.0 == tag).map_or(&[], |e| e.1)
}

pub fn values_for(tag: &str, attr: &str) -> &'static [&'static str] {
    let key = format!("{tag}.{attr}");
    VALUES.iter().find(|v| v.0 == key).or_else(|| VALUES.iter().find(|v| v.0 == attr)).map_or(&[], |v| v.1)
}

pub fn tag(name: &str) -> Option<&'static (&'static str, &'static str, &'static str, Option<&'static str>)> {
    TAGS.iter().find(|t| t.0 == name)
}

pub fn filter(name: &str) -> Option<&'static (&'static str, &'static str, &'static str)> {
    FILTERS.iter().find(|f| f.0 == name)
}

pub fn function(name: &str) -> Option<&'static (&'static str, &'static str, &'static str)> {
    FUNCTIONS.iter().find(|f| f.0 == name)
}

pub fn test(name: &str) -> Option<&'static (&'static str, &'static str, &'static str)> {
    TESTS.iter().find(|t| t.0 == name)
}
