declare(strict_types=1);

namespace Phem\Manifest;

use Symfony\Component\Filesystem\Path;
use Symfony\Component\HttpKernel\CacheWarmer\CacheWarmerInterface;

/**
 * Adds the compiled components to the OPcache preload of Symfony.
 *
 * In production, `config/preload.php` loads the `.preload.php` file of the container. This
 * warmer writes `phem-preload.php` in the build directory, and Symfony adds it to that file. It
 * loads the `autoload.php` of the phemc output.
 */
final class PreloadWarmer implements CacheWarmerInterface
{
    /** The file in the build directory of the kernel. */
    public const FILE = 'phem-preload.php';

    public function __construct(
        private readonly Manifest $manifest,
    ) {
    }

    public function isOptional(): bool
    {
        return false;
    }

    public function warmUp(string $cacheDir, ?string $buildDir = null): array
    {
        if (!$this->manifest->exists()) {
            return [];
        }

        $dir = $buildDir ?? $cacheDir;
        $autoload = $this->manifest->buildDir().'/autoload.php';

        // A relative path, so the cache stays valid when the project moves.
        $path = Path::isAbsolute($autoload) && Path::isAbsolute($dir)
            ? '__DIR__.'.var_export('/'.Path::makeRelative($autoload, $dir), true)
            : var_export($autoload, true);

        $file = $dir.'/'.self::FILE;
        file_put_contents($file, "<?php\n\n// Generated by Phem. OPcache preload: the compiled components.\n\nrequire_once {$path};\n");

        return [$file];
    }
}
